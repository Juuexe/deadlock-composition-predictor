import assert from 'node:assert/strict';
import test from 'node:test';
import { createApp } from '../src/server.ts';
import { trainModel } from '../src/model.ts';

test('browser API predicts valid teams and rejects bad input and private file paths', async t => {
  const teamA = [1, 2, 3, 4, 5, 6], teamB = [7, 8, 9, 10, 11, 12];
  const model = trainModel([{ matchId: 1, startedAt: '2026-01-01T00:00:00.000Z', teamA, teamB, winner: 'A' }], 0.01);
  const server = createApp(model, [...teamA, ...teamB].map(id => ({ id, name: `Hero ${id}` })));
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise<void>(resolve => { server.closeAllConnections(); server.close(() => resolve()); }));
  const address = server.address();
  if (!address || typeof address === 'string') throw new Error('Server did not start.');
  const base = `http://127.0.0.1:${address.port}`;
  const post = (body: unknown) => fetch(`${base}/api/predict`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const response = await post({ teamA, teamB });
  assert.equal(response.status, 200);
  const result = await response.json();
  assert.equal(result.status, 'experimental');
  assert.ok(result.teamAWinProbability > 0.5);
  assert.equal(result.heroSupport.length, 12);
  assert.equal((await post({ teamA, teamB: teamA })).status, 400);
  assert.equal((await post({ teamA, teamB, playerWinRate: 0.8 })).status, 400);
  assert.equal((await fetch(`${base}/api/predict`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{' })).status, 400);
  assert.equal((await fetch(`${base}/api/predict`, { method: 'POST', headers: { 'Content-Type': 'text/plain' }, body: '{}' })).status, 415);
  assert.equal((await fetch(`${base}/api/predict`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: 'x'.repeat(17000) })).status, 413);
  assert.equal((await fetch(`${base}/models/baseline.json`)).status, 404);
  assert.equal((await fetch(`${base}/.git/config`)).status, 404);
  const page = await fetch(base);
  assert.equal(page.status, 200);
  assert.ok(page.headers.get('content-security-policy')?.includes("default-src 'self'"));
});
